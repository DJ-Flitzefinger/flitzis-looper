//! Same-byte ONNX load control with fixed, nonlearned inline weights.
#[cfg(windows)]
#[allow(dead_code)]
#[path = "beat_this_audio/runtime.rs"]
mod runtime;

#[cfg(not(windows))]
fn main() -> Result<(), String> {
    Err("inline load control requires Windows".into())
}

#[cfg(windows)]
fn main() -> Result<(), String> {
    windows::run()
}

#[cfg(windows)]
mod windows {
    use super::runtime;
    use flitzis_looper_analysis::{
        inline_model,
        trial_lifetime::{Context, retain_first},
    };
    use ort::{
        ep,
        session::{Session, builder::GraphOptimizationLevel},
        value::Tensor,
    };
    use sha2::{Digest, Sha256};
    use std::{
        ffi::OsStr,
        io::Read,
        path::{Path, PathBuf},
    };

    // Generated by scripts/demucs_inline_load_fixture.py. No caller digest,
    // external initializer, learned graph or ORT-format bytes are eligible.
    const GRAPH_NAME: &str = "inline-load.onnx";
    const GRAPH_BYTES: usize = 134_217_914;
    const GRAPH_SHA256: &str = "c126c9dc313194ebc54d5eba442f3b01a2270824613e9b830370a74125cbb42d";
    const RUNTIME_MANIFEST: &str =
        "4929eb4f6a3aebe2c117850a2e1354c48bc004bfa5ff4d805c2ce0ecbef2915d";
    const RUNTIME_PACKAGE: &str =
        "7a5e216d9cc35418e8c38afa293ece04e86abc63153553fe56e81aa901cf2319";
    const WIDTH: usize = 4096;

    fn load(
        bytes: &[u8],
        profile: &Path,
        context: &Context,
    ) -> Result<(Session, runtime::Admission), String> {
        if format!("{:x}", Sha256::digest(bytes)) != GRAPH_SHA256 {
            return Err("inline load fixture digest mismatch".into());
        }
        let manifest = std::env::var_os(runtime::MANIFEST_ENV).ok_or("missing runtime manifest")?;
        let (admission, environment) =
            runtime::configure(Some((Path::new(&manifest), RUNTIME_MANIFEST)), context)?;
        let admission = admission.ok_or("missing runtime admission")?;
        runtime::commit(environment)?;
        let cpu = [ep::CPU::default()
            .with_arena_allocator(false)
            .build()
            .error_on_failure()];
        let session = (|| {
            Session::builder()?
                .with_no_environment_execution_providers()?
                .with_execution_providers(cpu)?
                .with_intra_threads(1)?
                .with_inter_threads(1)?
                .with_parallel_execution(false)?
                .with_intra_op_spinning(false)?
                .with_inter_op_spinning(false)?
                .with_memory_pattern(false)?
                .with_optimization_level(GraphOptimizationLevel::Disable)?
                .with_config_entry("session.disable_prepacking", "1")?
                .with_config_entry("session.load_model_format", "ONNX")?
                .with_profiling(profile)?
                .commit_from_memory(bytes)
        })()
        .map_err(|error| error.to_string())?;
        Ok((session, admission))
    }

    pub fn run() -> Result<(), String> {
        let args: Vec<_> = std::env::args_os().skip(1).map(PathBuf::from).collect();
        let [mode, graph, profile] = args.as_slice() else {
            return Err("expected mapped|copied GRAPH PROFILE_PREFIX".into());
        };
        if ort::MINOR_VERSION != 24
            || std::env::var(runtime::LOAD_POLICY_ENV).as_deref() != Ok("package-system32")
            || std::env::var(runtime::PACKAGE_DIGEST_ENV).as_deref() != Ok(RUNTIME_PACKAGE)
        {
            return Err("inline load control requires the pinned ORT 1.24.4/API 24 package".into());
        }
        let context = Context::new(None);
        if graph.file_name() != Some(OsStr::new(GRAPH_NAME)) {
            return Err("expected an absolute inline-load.onnx fixture path".into());
        }
        let (mut session, admission) = match mode.to_str() {
            Some("mapped") => inline_model::with_read_only(graph, GRAPH_BYTES, &context, |bytes| {
                load(bytes, profile, &context)
            }),
            Some("copied") => {
                let mut file = inline_model::open(graph, GRAPH_BYTES, &context)?;
                let mut bytes = vec![0; GRAPH_BYTES];
                let mut loaded = file
                    .read_exact(&mut bytes)
                    .map_err(|error| error.to_string())
                    .and_then(|()| load(&bytes, profile, &context));
                retain_first(&mut loaded, file.complete());
                loaded
            }
            _ => Err("expected mapped or copied fixture mode".into()),
        }?;

        // Run only after the file and the serialized bytes have been released.
        let input = Tensor::from_array(([1, WIDTH], vec![1.0f32; WIDTH]))
            .map_err(|error| error.to_string())?;
        let output = session
            .run(ort::inputs!["x" => input])
            .map_err(|error| error.to_string())?;
        for (name, period) in [("y1", 17), ("y2", 19)] {
            let (shape, values) = output
                .get(name)
                .ok_or("missing inline load output")?
                .try_extract_tensor::<f32>()
                .map_err(|error| error.to_string())?;
            if shape.as_ref() != [1, WIDTH as i64]
                || values.iter().enumerate().any(|(i, value)| {
                    let cell = (i % period) as i32 - (period / 2) as i32;
                    *value != (cell * WIDTH as i32) as f32
                })
            {
                return Err(format!("inline load output differs: {name}"));
            }
        }
        drop(output);
        let profile = session.end_profiling().map_err(|error| error.to_string())?;
        drop(session);
        context.cleanup()?;
        println!(
            "INLINE_LOAD {} {GRAPH_BYTES} {GRAPH_SHA256} {}",
            mode.display(),
            2 * WIDTH
        );
        println!("INLINE_LOAD_PROFILE {profile}");
        println!("INLINE_LOAD_RUNTIME {}", admission.receipt()?);
        Ok(())
    }
}
